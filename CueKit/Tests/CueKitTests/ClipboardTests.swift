    private func source(text: String? = nil, data: [String: Data] = [:], files: [String] = [], log: Reads = Reads()) -> CaptureSource {
        CaptureSource(text: {
            log.text += 1
            return text
        }, data: {
            log.types.append($0)
            return data[$0]
        }, files: {
            log.files += 1
            return files
        })
    }

