import CryptoKit
import Foundation
import Testing
@testable import CueKit

@Suite struct ClipboardTests {
    private let own = "app.cue.launcher.origin"
    private let text = CaptureFilter.plainTextType

    private func decide(_ types: [String], secure: Bool = false, app: String? = "com.apple.Safari",
                        content: String? = "hello", read: inout Bool) -> CaptureDecision {
        var didRead = false
        let result = CaptureFilter.decide(types: types, ownType: own, secureInput: secure, frontmostApp: app,
                                          excludedApps: ClipboardSettings.defaultExcludedApps) {
            didRead = true
            return content
        }
        read = didRead
        return result
    }

    @Test func skipFilterNeverReadsSensitiveContent() {
        var read = false
        #expect(decide([text, "org.nspasteboard.ConcealedType"], read: &read) == .skip(.concealed))
        #expect(!read)
        #expect(decide([text, "org.nspasteboard.TransientType"], read: &read) == .skip(.concealed))
        #expect(decide([text, "org.nspasteboard.AutoGeneratedType"], read: &read) == .skip(.concealed))
        #expect(decide([text, "com.agilebits.onepassword"], read: &read) == .skip(.concealed))
        #expect(decide([text, own], read: &read) == .skip(.ownWrite))
        #expect(decide([text], secure: true, read: &read) == .skip(.secureInput))
        #expect(!read)
        #expect(decide([text], app: "com.apple.passwords", read: &read) == .skip(.excludedApp))
        #expect(!read)
        #expect(decide(["public.png"], read: &read) == .skip(.notText))
        #expect(!read)
        #expect(decide([text], content: nil, read: &read) == .skip(.unreadable))
        #expect(decide([text], content: " \n\t", read: &read) == .skip(.blank))
        #expect(decide([text], content: String(repeating: "a", count: CaptureFilter.maxBytes + 1), read: &read) == .skip(.tooLarge))
        #expect(decide([text], content: String(repeating: "a", count: CaptureFilter.maxBytes), read: &read) != .skip(.tooLarge))
        #expect(decide([text, "public.rtf"], app: nil, read: &read) == .capture("hello"))
        #expect(read)
    }

    @Test func encryptionRoundTripsAndDetectsTampering() throws {
        let crypto = ClipboardCrypto(master: SymmetricKey(size: .bits256))
        let sealed = try crypto.seal("Olá 🌍", context: "a.text")
        #expect(try crypto.open(sealed, context: "a.text") == "Olá 🌍")
        #expect(!sealed.contains(Data("Olá".utf8)))
        var tampered = sealed
        tampered[tampered.count / 2] ^= 0x01
        #expect(throws: (any Error).self) { try crypto.open(tampered, context: "a.text") }
        #expect(throws: (any Error).self) { try crypto.open(sealed, context: "b.text") }
        #expect(throws: (any Error).self) { try ClipboardCrypto(master: SymmetricKey(size: .bits256)).open(sealed, context: "a.text") }
    }

    @Test func dedupeDigestIsStablePerKeyAndHidesText() {
        let key = SymmetricKey(size: .bits256)
        let a = ClipboardCrypto(master: key), b = ClipboardCrypto(master: key)
        #expect(a.digest("same") == b.digest("same"))
        #expect(a.digest("same") != a.digest("Same"))
        #expect(a.digest("same") != ClipboardCrypto(master: SymmetricKey(size: .bits256)).digest("same"))
        #expect(a.keyCheck == b.keyCheck)
        #expect(a.digest("same") != Data(SHA256.hash(data: Data("same".utf8))))
    }

    @Test func purgeHonorsRetentionMaxItemsAndPins() {
        let now = Date(timeIntervalSince1970: 1_000_000)
        func item(_ id: String, hoursAgo: Double, pinned: Bool = false) -> PurgeCandidate {
            PurgeCandidate(id: id, lastUsedAt: now.addingTimeInterval(-hoursAgo * 3600), pinned: pinned)
        }
        let items = [item("new", hoursAgo: 0.1), item("mid", hoursAgo: 2), item("old", hoursAgo: 48),
                     item("oldPinned", hoursAgo: 9000, pinned: true), item("newer", hoursAgo: 0.05)]
        #expect(ClipboardPurge.select(items, now: now, retention: .day, maxItems: 500) == ["old"])
        #expect(ClipboardPurge.select(items, now: now, retention: .hour, maxItems: 500) == ["mid", "old"])
        #expect(ClipboardPurge.select(items, now: now, retention: .never, maxItems: 2) == ["mid", "old"])
        #expect(ClipboardPurge.select(items, now: now, retention: .never, maxItems: 500).isEmpty)
    }

    @Test func searchIgnoresCaseAndDiacriticsAndSortsByLastUse() {
        let base = Date(timeIntervalSince1970: 0)
        let items = [
            ClipItem(id: "1", text: "Crème Brûlée recipe", source: nil, createdAt: base, lastUsedAt: base, pinboardID: nil),
            ClipItem(id: "2", text: "creme fraiche", source: nil, createdAt: base, lastUsedAt: base.addingTimeInterval(5), pinboardID: "p"),
            ClipItem(id: "3", text: "Ｆｕｌｌ width", source: nil, createdAt: base, lastUsedAt: base.addingTimeInterval(1), pinboardID: nil),
        ]
        #expect(ClipboardSearch.filter(items, query: "CREME").map(\.id) == ["2", "1"])
        #expect(ClipboardSearch.filter(items, query: "brulee").map(\.id) == ["1"])
        #expect(ClipboardSearch.filter(items, query: "full").map(\.id) == ["3"])
        #expect(ClipboardSearch.filter(items, query: "  ").map(\.id) == ["2", "3", "1"])
        #expect(ClipboardSearch.filter(items, query: "creme", pinboard: "p").map(\.id) == ["2"])
        #expect(ClipboardSearch.preview("\n  \n  first   line \nsecond") == "first line")
    }

    @Test func settingsValidation() throws {
        var settings = ClipboardSettings()
        try settings.validate()
        #expect(ClipboardSettings.isValidBundleID("com.example.My-App2"))
        for bad in ["", "com", "com..x", "com.exa mple", "../etc", "com.ex/ample", ".com.x"] {
            #expect(!ClipboardSettings.isValidBundleID(bad), "\(bad)")
        }
        settings.maxItems = 7
        #expect(throws: CueError.self) { try settings.validate() }
        settings = ClipboardSettings()
        settings.excludedApps += ["COM.APPLE.PASSWORDS"]
        #expect(throws: CueError.self) { try settings.validate() }
        settings = ClipboardSettings()
        settings.shortcut = "Shift+A"
        #expect(throws: CueError.self) { try settings.validate() }
        #expect(throws: CueError.self) { try Pinboard.validName("  ", existing: []) }
        #expect(throws: CueError.self) { try Pinboard.validName("work", existing: [Pinboard(id: "x", name: "Work")]) }
        #expect(try Pinboard.validName(" Work ", existing: [Pinboard(id: "x", name: "Work")], excluding: "x") == "Work")
    }

    @Test func exportCodecValidatesStrictly() throws {
        let board = UUID().uuidString.lowercased(), item = UUID().uuidString.lowercased()
        func file(_ edit: (inout [String: Any]) -> Void = { _ in }) throws -> Data {
            var object: [String: Any] = [
                "schemaVersion": 1, "exportedAt": "2026-10-22T10:00:00.000Z",
                "settings": ["retention": "7d", "maxItems": 500, "excludedApps": ["com.apple.Passwords"], "shortcut": NSNull()],
                "pinboards": [["id": board, "name": "Work"]],
                "items": [["id": item, "text": "hi", "createdAt": "2026-10-22T09:00:00Z", "lastUsedAt": "2026-10-22T09:30:00.000Z", "pinboardID": board]],
            ]
            edit(&object)
            return try JSONSerialization.data(withJSONObject: object)
        }
        let decoded = try ClipboardExport.decode(try file())
        #expect(decoded.items.first?.createdAt == "2026-10-22T09:00:00.000Z")
        #expect(decoded.settings.shortcut == nil)
        let reencoded = String(decoding: try decoded.encoded(), as: UTF8.self)
        #expect(reencoded.contains(#""pinboardID" : ""#) && reencoded.contains(#""shortcut" : null"#))
        #expect(try ClipboardExport.decode(try decoded.encoded()) == decoded)

        let broken: [(inout [String: Any]) -> Void] = [
            { $0["schemaVersion"] = 2 },
            { $0["schemaVersion"] = nil },
            { $0["settings"] = ["retention": "2d", "maxItems": 500, "excludedApps": []] },
            { $0["pinboards"] = [["id": board, "name": "A"], ["id": board, "name": "B"]] },
            { $0["pinboards"] = [["id": "not-a-uuid", "name": "A"]] },
            { $0["items"] = [["id": item, "text": "  ", "createdAt": "2026-10-22T09:00:00Z", "lastUsedAt": "2026-10-22T09:00:00Z", "pinboardID": NSNull()]] },
            { $0["items"] = [["id": item, "text": "x", "createdAt": "yesterday", "lastUsedAt": "2026-10-22T09:00:00Z", "pinboardID": NSNull()]] },
            { $0["items"] = [["id": item, "text": "x", "createdAt": "2026-10-22T09:00:00Z", "lastUsedAt": "2026-10-22T09:00:00Z", "pinboardID": UUID().uuidString.lowercased()]] },
            { $0["items"] = [["id": item, "text": 5]] },
        ]
        for edit in broken {
            #expect(throws: CueError.self) { try ClipboardExport.decode(try file(edit)) }
        }
        #expect(throws: CueError.self) { try ClipboardExport.decode(Data("[]".utf8)) }
    }

    @Test func storeRefusesNewerSchemaAndWrongKey() async throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let url = dir.appendingPathComponent(ClipboardStore.fileName)
        let store = try ClipboardStore(url: url)
        try await store.unlock(SymmetricKey(size: .bits256))
        try await store.capture("secret", source: nil, now: Date())
        await #expect(throws: ClipboardStore.keyUnavailable) { try await store.unlock(SymmetricKey(size: .bits256)) }
        try await store.resetHistory()
        try await store.unlock(SymmetricKey(size: .bits256))

        try SQLite(path: url).executeScript("PRAGMA user_version=99")
        #expect(throws: CueError.self) { try ClipboardStore(url: url) }
        #expect(try SQLite(path: url).userVersion() == 99)
    }

    @Test func settingsOnlyExportAndImportNeedNoKey() async throws {
        let source = try ClipboardStore(url: nil)
        var settings = await source.settings
        settings.retention = .day
        settings.shortcut = nil
        try await source.save(settings)
        let data = try await source.exportData(now: Date())
        let target = try ClipboardStore(url: nil)
        try await target.importData(data)
        #expect(await target.settings == settings)
        #expect(await !target.isUnlocked)
    }

    @Test func deletingPinboardUnpinsItemsOnDisk() async throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let url = dir.appendingPathComponent(ClipboardStore.fileName)
        let key = SymmetricKey(size: .bits256)
        let store = try ClipboardStore(url: url)
        try await store.unlock(key)
        let id = try await store.capture("keep me", source: nil, now: Date())
        let work = try await store.createPinboard("Work")
        try await store.setPinboard(id, work.id)
        try await store.deletePinboard(work.id)
        #expect(await store.items().first?.pinboardID == nil)

        let reopened = try ClipboardStore(url: url)
        try await reopened.unlock(key)
        #expect(await reopened.items().first?.pinboardID == nil)
        #expect(await reopened.pinboards.map(\.name) == ["Pinned"])
    }

    @Test func endToEndHappyPath() async throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: dir) }
        let url = dir.appendingPathComponent(ClipboardStore.fileName)
        let store = try ClipboardStore(url: url)
        try await store.unlock(SymmetricKey(size: .bits256))
        let t0 = Date(timeIntervalSince1970: 1_792_670_100)

        let first = try await store.capture("Meeting notes: Café at 10", source: "com.apple.Notes", now: t0)
        try await store.capture("https://example.com/path", source: "com.apple.Safari", now: t0.addingTimeInterval(60))
        let again = try await store.capture("Meeting notes: Café at 10", source: "com.apple.Notes", now: t0.addingTimeInterval(120))
        #expect(again == first)
        #expect(try await store.itemCount() == 2)
        #expect(await store.items().first?.id == first)

        let hits = ClipboardSearch.filter(await store.items(), query: "cafe")
        #expect(hits.map(\.id) == [first])
        #expect(hits.first?.source == "com.apple.Notes")

        let board = try await store.defaultPinboard()
        try await store.setPinboard(first, board.id)
        var settings = await store.settings
        settings.retention = .hour
        try await store.save(settings)
        #expect(try await store.purge(now: t0.addingTimeInterval(3 * 3600)) == 1)
        let fresh = try await store.capture("after purge", source: nil, now: t0.addingTimeInterval(3 * 3600))
        let expected = await store.items()
        #expect(expected.map(\.id) == [fresh, first])

        for suffix in ["", "-wal"] {
            let bytes = (try? Data(contentsOf: URL(fileURLWithPath: url.path + suffix))) ?? Data()
            #expect(!bytes.contains(Data("Meeting".utf8)) && !bytes.contains(Data("purge".utf8)) && !bytes.contains(Data("Notes".utf8)))
        }

        let exported = try await store.exportData(now: t0.addingTimeInterval(4 * 3600))
        let other = try ClipboardStore(url: dir.appendingPathComponent("other.sqlite3"))
        try await other.unlock(SymmetricKey(size: .bits256))
        try await other.importData(exported)
        let imported = await other.items()
        #expect(imported.map(\.id) == expected.map(\.id))
        #expect(imported.map(\.text) == expected.map(\.text))
        #expect(imported.map(\.lastUsedAt) == expected.map(\.lastUsedAt))
        #expect(imported.map(\.createdAt) == expected.map(\.createdAt))
        #expect(imported.map(\.pinboardID) == expected.map(\.pinboardID))
        #expect(await other.pinboards == store.pinboards)
        #expect(await other.settings == settings)
        #expect(ClipboardSearch.filter(imported, query: "CAFÉ").map(\.id) == [first])
        #expect(try await other.purge(now: t0.addingTimeInterval(3 * 3600)) == 0)

        await #expect(throws: CueError.self) { try await other.importData(Data("{\"schemaVersion\":1}".utf8)) }
        #expect(await other.items().map(\.id) == expected.map(\.id))

        try await store.clear(keepPinned: true)
        #expect(await store.items().map(\.id) == [first])
        try await store.clear(keepPinned: false)
        #expect(try await store.itemCount() == 0)
    }
}
