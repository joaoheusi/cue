    private func decide(_ types: [String], secure: Bool = false, app: String? = "com.apple.Safari",
                        content: String? = "hello", read: inout Bool) -> CaptureDecision {
        var didRead = false
        defer { read = didRead }
        if let reason = CaptureFilter.screen(types: types, ownType: own, secureInput: secure, frontmostApp: app,
                                             excludedApps: ClipboardSettings.defaultExcludedApps) { return .skip(reason) }
        let decision = CaptureFilter.read(types: types) {
            didRead = true
            return content
        }
        return CaptureFilter.review(decision, sensitive: .maskAndExpire)
    }

    @Test func skipFilterNeverReadsSensitiveContent() {
        var read = false
        #expect(decide([text, "org.nspasteboard.ConcealedType"], read: &read) == .skip(.concealed))
        #expect(!read)
        #expect(decide([text, "org.nspasteboard.TransientType"], read: &read) == .skip(.concealed))
        #expect(decide([text, "org.nspasteboard.AutoGeneratedType"], read: &read) == .skip(.concealed))
        #expect(decide([text, "com.agilebits.onepassword"], read: &read) == .skip(.concealed))
        #expect(decide([text, own], read: &read) == .skip(.ownWrite))
        #expect(decide([text], secure: true, read: &read) == .skip(.secureInput))
        #expect(!read)
        #expect(decide([text], app: "com.apple.passwords", read: &read) == .skip(.excludedApp))
        #expect(!read)
        #expect(decide(["public.png"], read: &read) == .skip(.unsupported))
        #expect(!read)
        #expect(decide([text], content: nil, read: &read) == .skip(.unreadable))
        #expect(decide([text], content: " \n\t", read: &read) == .skip(.blank))
        #expect(decide([text], content: String(repeating: "a", count: CaptureFilter.maxBytes + 1), read: &read) == .skip(.tooLarge))
        #expect(decide([text], content: String(repeating: "a", count: CaptureFilter.maxBytes), read: &read) != .skip(.tooLarge))
        #expect(decide([text, "public.rtf"], app: nil, read: &read) == .capture("hello"))
        #expect(read)
    }

    @Test func encryptionRoundTripsAndDetectsTampering() throws {
        let crypto = ClipboardCrypto(master: SymmetricKey(size: .bits256))
        let sealed = try crypto.seal("Olá 🌍", context: "a.text")
        #expect(try crypto.open(sealed, context: "a.text") == "Olá 🌍")
        #expect(!sealed.contains(Data("Olá".utf8)))
        var tampered = sealed
        tampered[tampered.count / 2] ^= 0x01
        #expect(throws: (any Error).self) { try crypto.open(tampered, context: "a.text") }
        #expect(throws: (any Error).self) { try crypto.open(sealed, context: "b.text") }
        #expect(throws: (any Error).self) { try ClipboardCrypto(master: SymmetricKey(size: .bits256)).open(sealed, context: "a.text") }
    }

    @Test func dedupeDigestIsStablePerKeyAndHidesText() {
