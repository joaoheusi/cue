    private func decide(_ types: [String], secure: Bool = false, app: String? = "com.apple.Safari",
                        content: String? = "hello", read: inout Bool) -> CaptureDecision {
        var didRead = false
        defer { read = didRead }
        if let reason = CaptureFilter.screen(types: types, ownType: own, secureInput: secure, frontmostApp: app,
                                             excludedApps: ClipboardSettings.defaultExcludedApps) { return .skip(reason) }
        let decision = CaptureFilter.readText(types: types) {
            didRead = true
            return content
        }
        return CaptureFilter.review(decision, sensitive: .maskAndExpire)
    }

    @Test func skipFilterNeverReadsSensitiveContent() {
        var read = false
        #expect(decide([text, "org.nspasteboard.ConcealedType"], read: &read) == .skip(.concealed))
        #expect(!read)
        #expect(decide([text, "org.nspasteboard.TransientType"], read: &read) == .skip(.concealed))
        #expect(decide([text, "org.nspasteboard.AutoGeneratedType"], read: &read) == .skip(.concealed))
        #expect(decide([text, "com.agilebits.onepassword"], read: &read) == .skip(.concealed))
        #expect(decide([text, own], read: &read) == .skip(.ownWrite))
        #expect(decide([text], secure: true, read: &read) == .skip(.secureInput))
        #expect(!read)
        #expect(decide([text], app: "com.apple.passwords", read: &read) == .skip(.excludedApp))
        #expect(!read)
        #expect(decide(["public.png"], read: &read) == .skip(.unsupported))
        #expect(!read)
        #expect(decide([text], content: nil, read: &read) == .skip(.unreadable))
        #expect(decide([text], content: " \n\t", read: &read) == .skip(.blank))
        #expect(decide([text], content: String(repeating: "a", count: CaptureFilter.maxTextBytes + 1), read: &read) == .skip(.tooLarge))
        #expect(decide([text], content: String(repeating: "a", count: CaptureFilter.maxTextBytes), read: &read) != .skip(.tooLarge))
        #expect(decide([text, "public.rtf"], app: nil, read: &read) == .capture(.plain("hello")))
        #expect(read)
    }

    private func encoded(_ uti: String, width: Int = 80, height: Int = 40, noise: Bool = false) throws -> Data {
        let context = try #require(CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                             space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(red: 0.2, green: 0.4, blue: 0.8, alpha: 1)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        if noise, let pixels = context.data {
            for offset in 0..<(context.bytesPerRow * height) { pixels.storeBytes(of: UInt8.random(in: 0...255), toByteOffset: offset, as: UInt8.self) }
        }
        let output = NSMutableData()
        let destination = try #require(CGImageDestinationCreateWithData(output, uti as CFString, 1, nil))
        CGImageDestinationAddImage(destination, try #require(context.makeImage()), nil)
        #expect(CGImageDestinationFinalize(destination))
        return output as Data
    }

    private final class Reads: @unchecked Sendable {
        var text = 0
        var types: [String] = []
        var files = 0
